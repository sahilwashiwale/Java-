package Operators;

public class TypeCast2 {

	public static void main(String[] args) {
		//Widening (implicit/Automatic) Casting
		//convert smaller datatype to larger datatype
		//no data loss,safe conversion,done auto by java
		
		int num=20;
		double num2 = num;
		System.out.println(num2);
	}

}
